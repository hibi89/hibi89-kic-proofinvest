"""P58: read-only issuer-supplied Apple FY2025 10-K HTML table-to-Engine-B crosscheck.

Accepts ACTUAL LOCAL HTML BYTES (not a URL), checks three financial
statement tables against P57 publisher/manual values, and records a byte
SHA. Matching labels/amounts and SHA do NOT authenticate SEC/issuer origin.
No downloader, HTTP, LLM, write, trade, or retained original.
"""
from __future__ import annotations

import argparse
from hashlib import sha256
from html.parser import HTMLParser
import json
from pathlib import Path
import re
import unicodedata
from typing import Any

from disclosure_lightning.originals import MAX_FILING_BYTES
from .apple_audited_10k_replay import TEN_K, replay_audited_10k_manual_excerpt
from .local_sec_packet import _read_regular_local
from .public_primary_baseline import APPLE, CURATED, _read

_MAX_TABLES = 2500
_MAX_ROWS = 50000
_MAX_CELLS = 100000
_MAX_CELL_TEXT = 2500
_MAX_VALUES = 15
_NUMBER = re.compile(r"\(?-?[0-9]{1,3}(?:,[0-9]{3})*\)?\Z")
_QUANTITY = re.compile(r"[0-9]{1,12}\Z")
_HEADERS = {
    "operations": ("total net sales", "gross margin",
                   "operating income", "net income", "total cost of sales"),
    "balance": ("total assets", "total liabilities", "total shareholders' equity",
                "accounts receivable, net", "inventories"),
    "cash": ("cash generated by operating activities",
             "payments for acquisition of property, plant and equipment"),
}
_METRICS = {
    "operations": {
        "total net sales": "sales",
        "total cost of sales": "cost_of_sales",
        "gross margin": "gross_margin",
        "operating income": "operating_income",
        "net income": "net_income",
    },
    "balance": {
        "total assets": "assets",
        "total liabilities": "liabilities",
        "total shareholders' equity": "equity",
        "accounts receivable, net": "accounts_receivable_net",
        "inventories": "inventory_net",
    },
    "cash": {
        "cash generated by operating activities": "operating_cashflow",
        "payments for acquisition of property, plant and equipment": "capex_payments",
    },
}


def _norm(value: str) -> str:
    value = unicodedata.normalize("NFKC", value).replace("\u2019", "'")
    return re.sub(r"\s+", " ", value).strip().casefold()


class _FinancialTables(HTMLParser):
    """Bounded HTML table extraction; ignores script/style and nested tables."""

    def __init__(self):
        super().__init__(convert_charrefs=True)
        self.tables: list[list[list[str]]] = []
        self.current: list[list[str]] | None = None
        self.nesting = 0
        self.row: list[str] | None = None
        self.cell: list[str] | None = None
        self.document_size = 0
        self.row_count = 0
        self.cell_count = 0
        self.cell_length = 0
        self.cell_overflow = False
        self.suppressed = 0
        self.seen_html = False

    def handle_starttag(self, tag: str, attrs: list[tuple[str, str | None]]):
        tag = tag.lower()
        if tag == "html":
            self.seen_html = True
        if tag in ("script", "style"):
            self.suppressed += 1
            return
        if self.suppressed:
            return
        if tag == "table":
            if self.current is None:
                if len(self.tables) >= _MAX_TABLES:
                    raise ValueError("FILING_TOO_MANY_TABLES")
                self.current = []
            self.nesting += 1
        if self.current is not None and self.nesting == 1:
            if tag == "tr":
                self.row = []
            elif tag in ("td", "th") and self.row is not None:
                self.cell_count += 1
                if self.cell_count > _MAX_CELLS:
                    raise ValueError("FILING_TOO_MANY_CELLS")
                self.cell = []
                self.cell_length = 0
                self.cell_overflow = False

    def handle_endtag(self, tag: str):
        tag = tag.lower()
        if tag in ("script", "style") and self.suppressed:
            self.suppressed -= 1
            return
        if self.suppressed or self.current is None:
            return
        if self.nesting == 1:
            if tag in ("td", "th") and self.cell is not None and self.row is not None:
                self.row.append("".join(self.cell).strip())
                self.cell = None
            elif tag == "tr" and self.row is not None:
                self.current.append(self.row)
                self.row_count += 1
                if self.row_count > _MAX_ROWS:
                    raise ValueError("FILING_TOO_MANY_ROWS")
                self.row = None
        if tag == "table":
            self.nesting -= 1
            if self.nesting < 0:
                raise ValueError("FILING_TABLE_STRUCTURE_INVALID")
            if self.nesting == 0:
                self.tables.append(self.current)
                self.current = None
                self.row = None
                self.cell = None

    def handle_data(self, data: str):
        if self.suppressed or self.nesting != 1 or self.cell is None:
            return
        self.document_size += len(data)
        if self.document_size > MAX_FILING_BYTES:
            raise ValueError("FILING_PARSED_TEXT_TOO_LARGE")
        # Inline XBRL may split a cell into thousands of nested spans.
        # After saturation, keep accounting for parsed input bytes without
        # reallocating the overflow marker on every subsequent fragment.
        if self.cell_overflow:
            return
        next_length = self.cell_length + len(data)
        if next_length > _MAX_CELL_TEXT:
            # Long legal text is irrelevant to numeric statement rows.
            self.cell = ["\uFFFD" * _MAX_CELL_TEXT]
            self.cell_length = _MAX_CELL_TEXT
            self.cell_overflow = True
        else:
            self.cell.append(data)
            self.cell_length = next_length


def _cells(row: list[str]) -> tuple[str, list[int]]:
    """Find label and first annual numeric values in split SEC table cells."""
    meaningful = [(i, _norm(raw)) for i, raw in enumerate(row)
                  if _norm(raw) not in ("", "$", "\uFFFD")]
    if not meaningful:
        return "", []
    label_idx, label = meaningful[0]
    if _NUMBER.fullmatch(label):
        return "", []
    values: list[int] = []
    for i in range(label_idx + 1, len(row)):
        cell = _norm(row[i]).replace(" ", "")
        if not _NUMBER.fullmatch(cell):
            continue
        wrapped = cell.startswith("(") and cell.endswith(")")
        plain = cell.strip("()-").replace(",", "")
        if not _QUANTITY.fullmatch(plain):
            continue
        signed = -int(plain) if wrapped or cell.startswith("-") else int(plain)
        # Some inline XBRL layouts split opening/closing parentheses into
        # adjacent cells instead of wrapping the same numeric cell.
        if i > 0 and _norm(row[i-1]).endswith("("):
            signed = -abs(signed)
        values.append(signed)
        if len(values) > _MAX_VALUES:
            raise ValueError("FILING_ROW_NUMERIC_VALUE_OVERFLOW")
    return label, values


def _statement_rows(tables: list[list[list[str]]], kind: str) -> dict[str, list[int]]:
    required = set(_HEADERS[kind])
    candidates = []
    for rows in tables:
        labeled: dict[str, list[list[int]]] = {}
        for row in rows:
            label, vals = _cells(row)
            if label:
                labeled.setdefault(label, []).append(vals)
        if all(k in labeled for k in required):
            candidates.append(labeled)
    if len(candidates) != 1:
        raise ValueError("FILING_" + kind.upper() + "_TABLE_MISSING_OR_AMBIGUOUS")
    found = candidates[0]
    for label in required:
        if len(found[label]) != 1 or len(found[label][0]) < 2:
            raise ValueError("FILING_" + kind.upper() + "_ROW_MISSING_OR_AMBIGUOUS")
    return {k: v[0][:2] for k, v in found.items() if k in required}


def verify_local_apple_10k_html(
    original_html: bytes, manual_10k: Any, press_release: Any,
    curated_revenue: Any,
) -> dict[str, Any]:
    """Real byte/file table comparison, not SEC network/source authentication."""
    if (type(original_html) is not bytes or not 0 < len(original_html) <= MAX_FILING_BYTES
            or b"\x00" in original_html):
        raise ValueError("LOCAL_HTML_BYTES_INVALID")
    # Validate the prior independently checked issuer figures and actual Engine
    # B arithmetic BEFORE reading potentially untrusted filing table content.
    baseline = replay_audited_10k_manual_excerpt(
        manual_10k, press_release, curated_revenue)
    try:
        html = original_html.decode("utf-8-sig")
    except UnicodeDecodeError:
        raise ValueError("LOCAL_HTML_UTF8_REQUIRED") from None
    if not re.search(r"<html(?:\s|>)", html[:10000], flags=re.I):
        raise ValueError("LOCAL_HTML_DOCUMENT_REQUIRED")
    if "Apple Inc." not in html or "10-K" not in html:
        raise ValueError("LOCAL_HTML_ISSUER_MARKERS_MISSING")
    parser = _FinancialTables()
    try:
        parser.feed(html)
        parser.close()
    except (RecursionError, ValueError) as exc:
        raise ValueError("LOCAL_HTML_TABLE_PARSE_FAILED") from exc
    if not parser.seen_html or not parser.tables:
        raise ValueError("LOCAL_HTML_STATEMENTS_MISSING")
    passed = []
    for statement in _METRICS:
        rows = _statement_rows(parser.tables, statement)
        for label, field in _METRICS[statement].items():
            actual = rows[label]
            for i, period in enumerate(("current", "prior")):
                expected = int(manual_10k[period][field])
                if field == "capex_payments":
                    # Apple cash flow statement reports payments with negative
                    # parentheses, while source manifest stores absolute spend.
                    expected = -expected
                if actual[i] != expected:
                    raise ValueError("LOCAL_HTML_" + statement.upper()
                                     + "_ORIGINAL_VS_MANUAL_CONFLICT")
                passed.append(statement + ":" + field + ":" + period)
    return {
        "schema": "kuodra.apple-local-html-statements-crosscheck.v1",
        "status": "LOCAL_ORIGINAL_HTML_BYTES_MATCH_MANUAL_FINANCIAL_ROWS_ORIGIN_UNVERIFIED",
        "issuer": "Apple Inc.", "accession_claimed": manual_10k["accession"],
        "original_local_html_sha256": sha256(original_html).hexdigest(),
        "original_local_html_size": len(original_html),
        "parsed_html_tables": len(parser.tables),
        "matched_numeric_cells": len(passed),
        "statements_matched": ["operations", "balance", "cash"],
        "manual_p57_engine_b_replay_status": baseline["status"],
        "sec_original_file_authenticated": False,
        "issuer_original_file_authenticated": False,
        "origin_url_authenticated": False,
        "sec_companyfacts_original_authenticated": False,
        "sec_submissions_original_authenticated": False,
        "data_rights_verified": False,
        "full_sec_guard_a_b_c_real_data_verified": False,
        "original_bytes_retained": False,
        "network_requests": 0, "trade_executed": False,
        "limitations": [
            "SHA-256 confirms only the exact local HTML bytes supplied, not the publisher origin.",
            "Matching table rows and reported values do not prove that the supplied file came from Apple or the SEC.",
            "The prior P57 input is a human-reviewed issuer excerpt, not a raw SEC CompanyFacts response.",
            "SEC 3-source, market, sector, provider license and production verification remain pending.",
        ],
    }


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Read-only local issuer 10-K HTML table comparison; no network")
    parser.add_argument("--original-html", type=Path, required=True)
    parser.add_argument("--manual-10k", type=Path, default=TEN_K)
    parser.add_argument("--press-release", type=Path, default=APPLE)
    parser.add_argument("--curated", type=Path, default=CURATED)
    args = parser.parse_args(argv)
    output = verify_local_apple_10k_html(
        _read_regular_local(args.original_html, MAX_FILING_BYTES),
        _read(args.manual_10k), _read(args.press_release), _read(args.curated))
    print(json.dumps(output, sort_keys=True, ensure_ascii=True, indent=2))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
