"""P58 byte-level Apple 10-K HTML parsing gate; HTML specimens are synthetic.

These tests do NOT claim a real Apple original HTML was downloaded, or SEC
origin authenticated. Real approved issuer files must be supplied locally.
"""
from __future__ import annotations

from contextlib import redirect_stdout
from copy import deepcopy
from hashlib import sha256
from io import StringIO
import json
from pathlib import Path
from tempfile import TemporaryDirectory
import unittest
from unittest.mock import patch

from proofinvest.apple_local_html_crosscheck import (
    _FinancialTables, _cells, verify_local_apple_10k_html, main,
)
from proofinvest.apple_audited_10k_replay import TEN_K
from proofinvest.public_primary_baseline import APPLE, CURATED, _read


def _table(rows):
    return "<table>" + "".join(
        "<tr><td>" + name + "</td><td>$</td><td>" + a
        + "</td><td></td><td>$</td><td>" + b + "</td></tr>"
        for name, a, b in rows
    ) + "</table>"


def sample_html():
    """Small constructed table fixture with independently literal real numbers."""
    ops = _table([
        ("Products", "307,003", "294,866"),
        ("Services", "109,158", "96,169"),
        ("Total net sales", "416,161", "391,035"),
        ("Total cost of sales", "220,960", "210,352"),
        ("Gross margin", "195,201", "180,683"),
        ("Operating income", "133,050", "123,216"),
        ("Net income", "112,010", "93,736"),
    ])
    balance = _table([
        ("Accounts receivable, net", "39,777", "33,410"),
        ("Inventories", "5,718", "7,286"),
        ("Total assets", "359,241", "364,980"),
        ("Total liabilities", "285,508", "308,030"),
        ("Total shareholders’ equity", "73,733", "56,950"),
    ])
    cash = _table([
        ("Net income", "112,010", "93,736"),
        ("Cash generated by operating activities", "111,482", "118,254"),
        ("Payments for acquisition of property, plant and equipment",
         "(12,715)", "(9,447)"),
    ])
    return (
        "<!doctype html><html lang='en'><body><h1>Apple Inc. FORM 10-K</h1>"
        + "<h2>CONSOLIDATED STATEMENTS OF OPERATIONS</h2>" + ops
        + "<h2>CONSOLIDATED BALANCE SHEETS</h2>" + balance
        + "<h2>CONSOLIDATED STATEMENTS OF CASH FLOWS</h2>" + cash
        + "<script>Fake secret table numeric 999,999</script></body></html>"
    ).encode("utf-8")


class AppleOriginalHTMLTests(unittest.TestCase):
    def setUp(self):
        self.doc = _read(TEN_K)
        self.press = _read(APPLE)
        self.curated = _read(CURATED)

    def run_gate(self, raw=None, doc=None):
        return verify_local_apple_10k_html(
            sample_html() if raw is None else raw,
            self.doc if doc is None else doc,
            self.press, self.curated,
        )

    def test_three_statements_and_raw_byte_sha(self):
        raw = sample_html()
        with patch("urllib.request.urlopen", side_effect=AssertionError("NO_NETWORK")) as net:
            result = self.run_gate(raw=raw)
        net.assert_not_called()
        self.assertEqual(result["status"],
                         "LOCAL_ORIGINAL_HTML_BYTES_MATCH_MANUAL_FINANCIAL_ROWS_ORIGIN_UNVERIFIED")
        self.assertEqual(result["matched_numeric_cells"], 24)
        self.assertEqual(result["statements_matched"], ["operations", "balance", "cash"])
        self.assertEqual(result["original_local_html_sha256"], sha256(raw).hexdigest())
        self.assertEqual(result["original_local_html_size"], len(raw))
        self.assertEqual(result["parsed_html_tables"], 3)
        self.assertFalse(result["issuer_original_file_authenticated"])
        self.assertFalse(result["sec_original_file_authenticated"])
        self.assertFalse(result["full_sec_guard_a_b_c_real_data_verified"])
        self.assertFalse(result["original_bytes_retained"])
        self.assertEqual(result["network_requests"], 0)

    def test_source_manifest_and_original_are_unchanged(self):
        before = deepcopy((self.doc, self.press, self.curated))
        self.run_gate()
        self.assertEqual((self.doc, self.press, self.curated), before)

    def test_real_statement_values_mismatch_denied_even_if_arithmetic_possible(self):
        for old, replacement in (
            (b"416,161", b"416,162"),
            (b"359,241", b"359,242"),
            (b"285,508", b"285,509"),
            (b"111,482", b"111,483"),
            (b"(12,715)", b"(12,716)"),
        ):
            specimen = sample_html().replace(old, replacement)
            with self.subTest(value=old), self.assertRaisesRegex(
                ValueError, r"LOCAL_HTML_(OPERATIONS|BALANCE|CASH)_ORIGINAL_VS_MANUAL_CONFLICT",
            ):
                self.run_gate(raw=specimen)

    def test_fabricated_competing_table_fails_closed(self):
        raw = sample_html()
        table_start = raw.index(b"<table>")
        table_end = raw.index(b"</table>", table_start) + len(b"</table>")
        injected = raw.replace(b"</body>", raw[table_start:table_end] + b"</body>")
        with self.assertRaisesRegex(ValueError, "OPERATIONS_TABLE_MISSING_OR_AMBIGUOUS"):
            self.run_gate(raw=injected)

    def test_missing_required_metric_or_incorrect_sign_fails(self):
        for old, new in (
            (b"Gross margin", b"Margin"),
            (b"Total shareholders", b"Shareholders"),
            (b"Cash generated by operating activities", b"Operating activities"),
            (b"(12,715)", b"12,715"),
        ):
            with self.subTest(change=old), self.assertRaises(ValueError):
                self.run_gate(raw=sample_html().replace(old, new))

    def test_year_order_reverse_denied(self):
        raw = sample_html().replace(
            b"<td>416,161</td><td></td><td>$</td><td>391,035</td>",
            b"<td>391,035</td><td></td><td>$</td><td>416,161</td>",
        )
        with self.assertRaisesRegex(ValueError, "OPERATIONS_ORIGINAL_VS_MANUAL_CONFLICT"):
            self.run_gate(raw=raw)

    def test_duplicate_metric_row_within_statement_fails(self):
        raw = sample_html().replace(
            b"<tr><td>Gross margin</td>",
            b"<tr><td>Gross margin</td><td>195,201</td><td>180,683</td></tr>"
            b"<tr><td>Gross margin</td>",
        )
        with self.assertRaisesRegex(ValueError, "OPERATIONS_ROW_MISSING_OR_AMBIGUOUS"):
            self.run_gate(raw=raw)

    def test_no_wrong_source_manifest_upgrade(self):
        bad = deepcopy(self.doc)
        bad["source"]["original_sec_api_authenticated"] = True
        with self.assertRaises(ValueError):
            self.run_gate(doc=bad)

    def test_binary_and_oversized_html_denied(self):
        for raw in (b"\x00<html>Apple Inc. FORM 10-K</html>", b"not html",
                    b"<html>Apple Inc. FORM 10-K \xff</html>"):
            with self.subTest(data=raw[:12]), self.assertRaises(ValueError):
                self.run_gate(raw=raw)
        with patch("proofinvest.apple_local_html_crosscheck.MAX_FILING_BYTES", 100):
            with self.assertRaisesRegex(ValueError, "LOCAL_HTML_BYTES_INVALID"):
                self.run_gate()

    def test_split_parenthesis_and_nested_text_parsing(self):
        label, vals = _cells(["Cash generated by operating activities", "$", "111,482",
                              "$", "118,254"])
        self.assertEqual(label, "cash generated by operating activities")
        self.assertEqual(vals, [111482, 118254])
        label, vals = _cells(["Capex", "(", "12,715", ")", "(", "9,447", ")"])
        self.assertEqual(vals, [-12715, -9447])

    def test_empty_html_cell_flood_is_bounded_even_without_numeric_text(self):
        parser = _FinancialTables()
        malicious = "<html><table><tr>" + "<td></td>" * 8 + "</tr></table></html>"
        with patch("proofinvest.apple_local_html_crosscheck._MAX_CELLS", 7):
            with self.assertRaisesRegex(ValueError, "FILING_TOO_MANY_CELLS"):
                parser.feed(malicious)
        with patch("proofinvest.apple_local_html_crosscheck._MAX_CELLS", 10):
            with self.assertRaisesRegex(ValueError, "LOCAL_HTML_TABLE_PARSE_FAILED"):
                self.run_gate()

    def test_fragmented_inline_tags_preserve_bounded_cell_text(self):
        # Thousands of fragments must remain linear-time, even if the HTML
        # input stays below the original byte-size limit.
        parser = _FinancialTables()
        raw = "<html><table><tr><td>" + "<span>1</span>" * 5000
        raw += "</td></tr></table></html>"
        parser.feed(raw)
        parser.close()
        self.assertEqual(parser.tables, [[[ "\uFFFD" * 2500 ]]])
        self.assertEqual(parser.cell_length, 2500)
        self.assertEqual(parser.cell_count, 1)

    def test_saturated_cell_does_not_reallocate_overflow_marker(self):
        parser = _FinancialTables()
        with patch("proofinvest.apple_local_html_crosscheck._MAX_CELL_TEXT", 7):
            parser.feed("<html><table><tr><td>1234567")
            parser.feed("<span>8</span>")
            self.assertTrue(parser.cell_overflow)
            marker = parser.cell[0]
            parser.feed("<span>9</span>" * 5000)
            self.assertIs(parser.cell[0], marker)
            self.assertEqual(parser.cell_length, 7)
            self.assertEqual(parser.document_size, 5008)
            parser.feed("</td></tr></table></html>")
        self.assertEqual(parser.tables, [[["\uFFFD" * 7]]])

    def test_total_parsed_byte_limit_still_applies_after_saturation(self):
        parser = _FinancialTables()
        with patch("proofinvest.apple_local_html_crosscheck._MAX_CELL_TEXT", 7), \
             patch("proofinvest.apple_local_html_crosscheck.MAX_FILING_BYTES", 8):
            parser.feed("<html><table><tr><td>1234567")
            parser.feed("8")
            self.assertTrue(parser.cell_overflow)
            with self.assertRaisesRegex(ValueError, "FILING_PARSED_TEXT_TOO_LARGE"):
                parser.feed("9")

    def test_cli_invalid_local_file_returns_sanitized_json_exit_2(self):
        with TemporaryDirectory() as folder:
            path = Path(folder) / "private-issuer-original.htm"
            path.write_bytes(sample_html().replace(b"416,161", b"416,162"))
            stdout = StringIO()
            with redirect_stdout(stdout):
                exit_code = main(["--original-html", str(path)])
            self.assertEqual(exit_code, 2)
            record = json.loads(stdout.getvalue())
            self.assertEqual(record["status"], "blocked")
            self.assertEqual(record["reason_code"],
                             "LOCAL_HTML_OPERATIONS_ORIGINAL_VS_MANUAL_CONFLICT")
            self.assertFalse(record["sec_original_file_authenticated"])
            self.assertFalse(record["original_bytes_retained"])
            self.assertNotIn(str(path), stdout.getvalue())
            self.assertNotIn("416,162", stdout.getvalue())

    def test_cli_missing_file_is_blocked_without_path_disclosure(self):
        with TemporaryDirectory() as folder:
            path = Path(folder) / "DO_NOT_LEAK_missing_10k_original.htm"
            stdout = StringIO()
            with redirect_stdout(stdout):
                exit_code = main(["--original-html", str(path)])
            record = json.loads(stdout.getvalue())
            self.assertEqual(exit_code, 2)
            self.assertEqual(record["reason_code"], "LOCAL_SOURCE_REVIEW_BLOCKED")
            self.assertNotIn(str(path), stdout.getvalue())
            self.assertEqual(record["network_requests"], 0)

    def test_cli_untrusted_exception_text_is_not_exposed(self):
        with TemporaryDirectory() as folder:
            path = Path(folder) / "local.htm"
            path.write_bytes(sample_html())
            stdout = StringIO()
            with patch("proofinvest.apple_local_html_crosscheck.verify_local_apple_10k_html",
                       side_effect=ValueError("PRIVATE_SECRET_DO_NOT_EMIT")), \
                 redirect_stdout(stdout):
                exit_code = main(["--original-html", str(path)])
            self.assertEqual(exit_code, 2)
            self.assertEqual(json.loads(stdout.getvalue())["reason_code"],
                             "LOCAL_SOURCE_REVIEW_BLOCKED")
            self.assertNotIn("PRIVATE_SECRET", stdout.getvalue())

    def test_cli_local_file_path_and_json_receipt(self):
        raw = sample_html()
        with TemporaryDirectory() as folder:
            path = Path(folder) / "local-issuer-10k.html"
            path.write_bytes(raw)
            out = StringIO()
            with patch("urllib.request.urlopen", side_effect=AssertionError("NO_HTTP")), \
                 redirect_stdout(out):
                self.assertEqual(main(["--original-html", str(path)]), 0)
            result = json.loads(out.getvalue())
            self.assertEqual(result["original_local_html_sha256"], sha256(raw).hexdigest())
            self.assertNotIn(str(path), out.getvalue())
            self.assertNotIn("raw_html", result)
            self.assertFalse(result["data_rights_verified"])


if __name__ == "__main__":
    unittest.main()
